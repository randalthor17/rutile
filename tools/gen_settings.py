#!/usr/bin/env python3
"""Generate shell/services/SettingsSchema.js from settings/schema.json (D45).

    gen_settings.py            write the file
    gen_settings.py --check    exit 1 if it is stale or the schema is not one we support

The schema is the one source for every setting: the shell gets it through this file, and the home-manager
module (nix/home-manager.nix) reads the JSON itself. Both understand only a small part of JSON Schema, so this
checks that the schema keeps to it: objects of properties, and leaves of type boolean, integer, number, string,
or array of those, with optional enum, minimum, maximum, default, title and description.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "settings" / "schema.json"
OUT = ROOT / "shell" / "services" / "SettingsSchema.js"
MARK = "// GENERATED by tools/gen_settings.py from settings/schema.json, do not edit. Run `make generate`."

SCALARS = {"boolean", "integer", "number", "string"}
DOC_KEYS = {"title", "description"}
ROOT_KEYS = {"$schema"} | DOC_KEYS | {"type", "properties"}
OBJECT_KEYS = DOC_KEYS | {"type", "properties"}
LEAF_KEYS = DOC_KEYS | {"type", "items", "enum", "minimum", "maximum", "default"}


def scalar_ok(kind, value):
    if kind == "boolean":
        return isinstance(value, bool)
    if kind == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if kind == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    return isinstance(value, str)


def value_ok(leaf, value):
    """Whether `value` fits the leaf: what the shell's SettingsStore.valid() accepts."""
    if leaf["type"] == "array":
        return isinstance(value, list) and all(value_ok(leaf["items"], v) for v in value)
    if not scalar_ok(leaf["type"], value):
        return False
    if "enum" in leaf and value not in leaf["enum"]:
        return False
    if "minimum" in leaf and value < leaf["minimum"]:
        return False
    return not ("maximum" in leaf and value > leaf["maximum"])


def problems(schema):
    """What in the schema the shell or the Nix module would not understand, as messages."""
    out = []

    def leaf(path, node):
        extra = set(node) - LEAF_KEYS
        if extra:
            out.append(f"{path}: unsupported keys {sorted(extra)}")
        kind = node.get("type")
        if not isinstance(kind, str):           # JSON Schema allows a list of types; we do not
            out.append(f"{path}: type must be one name")
            return
        if kind == "array":
            items = node.get("items")
            if not isinstance(items, dict) or not isinstance(items.get("type"), str) or items["type"] not in SCALARS:
                out.append(f"{path}: an array's items must be one of {sorted(SCALARS)}")
            else:
                leaf(path + "[]", items)        # a scalar: checked just above
        elif kind not in SCALARS:
            out.append(f"{path}: type must be one of {sorted(SCALARS)} or array")
            return
        if "default" in node and not value_ok(node, node["default"]):
            out.append(f"{path}: the default does not fit the type and limits")

    def obj(path, node, keys):
        extra = set(node) - keys
        if extra:
            out.append(f"{path or 'root'}: unsupported keys {sorted(extra)}")
        if node.get("type") != "object" or not isinstance(node.get("properties"), dict):
            out.append(f"{path or 'root'}: must be an object with properties")
            return
        for name, child in node["properties"].items():
            sub = f"{path}.{name}" if path else name
            if not name.replace("_", "").isalnum() or not name[0].isalpha():
                out.append(f"{sub}: names are letters, digits and _ (they become Nix option names)")
            if child.get("type") == "object":
                obj(sub, child, OBJECT_KEYS)
            else:
                leaf(sub, child)

    obj("", schema, ROOT_KEYS)
    return out


def build():
    schema = json.loads(SCHEMA.read_text())
    return schema, (MARK + "\n// Every setting (D45); SettingsStore.js reads it.\n.pragma library\n\nvar schema = "
                    + json.dumps(schema, indent=4) + ";\n")


def main(argv):
    schema, text = build()
    bad = problems(schema)
    if bad:
        print("settings/schema.json:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 1
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale generated {OUT.relative_to(ROOT)}; run `make generate`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
