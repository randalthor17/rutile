#!/usr/bin/env python3
"""Generate shell/widgethost/SourceCatalog.js from widgets/sources.json (plan 4.2, D79), and
shell/widgethost/SpecSchema.js from widgets/spec.schema.json (the shell's widget check, plan 4.6, D85).

    gen_sources.py            write the files
    gen_sources.py --check    exit 1 if one is stale

The catalog is the one list of the widget data sources and their fields: tools/widget_check.py reads the JSON,
the renderer this file (which fields exist, which are lists, which are open documents).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "widgets" / "sources.json"
OUT = ROOT / "shell" / "widgethost" / "SourceCatalog.js"
MARK = "// GENERATED by tools/gen_sources.py from widgets/sources.json, do not edit. Run `make generate`."
SCHEMA = ROOT / "widgets" / "spec.schema.json"
SCHEMA_OUT = ROOT / "shell" / "widgethost" / "SpecSchema.js"
SCHEMA_MARK = "// GENERATED by tools/gen_sources.py from widgets/spec.schema.json, do not edit. Run `make generate`."


def render():
    catalog = json.loads(SOURCES.read_text())["sources"]
    slim = {}
    for name, entry in catalog.items():
        fields = {}
        for field, f in entry["fields"].items():
            fields[field] = {"type": f["type"]}
            if f["type"] == "list":
                fields[field]["item"] = list(f["item"])          # in the file's order, as messages list them
        slim[name] = {"open": bool(entry.get("open")), "fields": fields}
    return (MARK + "\n// The widget data sources and their fields (plan 4.2); WidgetSpec.js reads it.\n.pragma library\n\n"
            "var sources = " + json.dumps(slim, indent=4) + ";\n")


def render_schema():
    schema = json.loads(SCHEMA.read_text())
    return (SCHEMA_MARK + "\n// The widget spec v1 (plan 4.1); WidgetCheck.js checks widgets against it.\n.pragma library\n\n"
            "var schema = " + json.dumps(schema, indent=4, ensure_ascii=False) + ";\n")


def main(argv):
    outputs = {OUT: render(), SCHEMA_OUT: render_schema()}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale: run `make generate`")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
