#!/usr/bin/env python3
"""Generate the token singletons in shell/common/ from tokens/m3e.json and
theme/roles.json (+ the golden palette as the built-in fallback colors).

    gen_qml.py            write the files
    gen_qml.py --check    exit 1 if any generated file is stale

Generated files start with a GENERATED marker, which also exempts them from
tools/lint_hardcoded.py (they are where design values live).
"""
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "shell" / "common"
MARK = "// GENERATED by tools/gen_qml.py, do not edit. Run `make generate`."


def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def qml_name(role):
    """QML property name for a color role.

    QML treats properties named `on` + Capital as signal handlers, so on_primary
    cannot be `onPrimary`. `on_*` roles get a trailing On instead: primaryOn.
    """
    if role.startswith("on_"):
        return camel(role[3:]) + "On"
    return camel(role)


def js(value):
    return json.dumps(value, separators=(", ", ": "))


def header(extra, qt="QtQml"):
    # `color` is a QtQuick basic type; pure-data singletons only need QtQml.
    return f"{MARK}\n// {extra}\npragma Singleton\nimport {qt}\n\n"


def gen_shapes(t):
    corners = t["shape"]["corner_dp"]
    lines = [header("Corner radii in px from tokens/m3e.json (M3 shape scale).") + "QtObject {"]
    for name, v in sorted(corners.items(), key=lambda kv: (kv[1] == "full", kv[1] if kv[1] != "full" else 0)):
        # QML clamps radius to half the shorter side, so a large value gives a pill.
        lines.append(f"    readonly property int {camel(name)}: {9999 if v == 'full' else v}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_elevation(t):
    lines = [header("Elevation levels in px from tokens/m3e.json.") + "QtObject {"]
    for name, v in t["elevation"]["dp"].items():
        lines.append(f"    readonly property int {name}: {v}")
    lines.append("}")
    return "\n".join(lines) + "\n"


# A critically damped spring released from rest follows x(t) = 1 - (1 + wt) e^(-wt), w = sqrt(stiffness).
# It comes within 1/255 of its target (no visible change left in an 8-bit color) at wt = SETTLE_WT, and
# on that normalized time this cubic bezier stays within 1.8% of it without overshooting (fitted by a grid
# search; tests/test_gen_qml.py checks the error). Effects springs are critically damped, so a
# ColorAnimation or NumberAnimation with this curve replaces a per-frame JavaScript spring.
SETTLE_WT = 7.705182
CRITICAL_BEZIER = [0.24, 0.28, 0.12, 1.0]


def effects_curves(springs):
    out = {}
    for speed, p in springs.items():
        if p["damping_ratio"] != 1:
            raise ValueError(f"effects spring {speed} is not critically damped; CRITICAL_BEZIER does not apply")
        out[speed] = {"duration": round(SETTLE_WT / math.sqrt(p["stiffness"]) * 1000),
                      "bezier": CRITICAL_BEZIER + [1, 1]}
    return out


def gen_motion(t):
    m = t["motion"]
    out = [header("Durations (ms), easing curves and spring parameters from tokens/m3e.json.") + "QtObject {"]
    out.append("    // \"expressive\" (default) or \"standard\"; selects which spring set spring() returns.")
    out.append('    property string scheme: "expressive"')
    out.append("")
    for name, v in m["duration_ms"].items():
        out.append(f"    readonly property int {camel(name)}: {v}")
    out.append("")
    out.append("    // Cubic beziers as QML easing.bezierCurve arrays: [x1, y1, x2, y2, 1, 1].")
    easing = {camel(k): v + [1, 1] for k, v in m["easing_cubic_bezier"].items()}
    out.append(f"    readonly property var easing: ({js(easing)})")
    out.append("")
    out.append("    // stiffness is M3/Compose stiffness (mass 1); dampingRatio is the damping ratio.")
    springs = {}
    for scheme in ("expressive", "standard"):
        springs[scheme] = {
            axis: {speed: {"stiffness": p["stiffness"], "dampingRatio": p["damping_ratio"]}
                   for speed, p in speeds.items()}
            for axis, speeds in m[scheme].items()
        }
    out.append(f"    readonly property var springs: ({js(springs)})")
    out.append("")
    out.append("    // The effects springs as a duration (ms) and easing curve, for Behavior animations (see gen_qml.py).")
    curves = {scheme: effects_curves(m[scheme]["effects"]) for scheme in ("expressive", "standard")}
    out.append(f"    readonly property var effectsCurves: ({js(curves)})")
    out.append("")
    out.append("    // axis: \"spatial\" | \"effects\"; speed: \"fast\" | \"default\" | \"slow\"")
    out.append("    function spring(axis, speed) {")
    out.append("        return springs[scheme][axis][speed];")
    out.append("    }")
    out.append("")
    out.append("    // speed: \"fast\" | \"default\" | \"slow\"; returns {duration, bezier}")
    out.append("    function effects(speed) {")
    out.append("        return effectsCurves[scheme][speed];")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_type(t, fonts):
    styles = t["type"]["styles"]
    out = [header("Type scale from tokens/m3e.json (sp treated as px; tracking in px).", qt="QtQuick") + "QtObject {"]
    out.append("    // Families come from theme/fonts.json; both M3 font roles use the same family.")
    out.append(f'    property string plainFamily: "{fonts["text"]["family"]}"')
    out.append(f'    property string brandFamily: "{fonts["text"]["family"]}"')
    out.append("")
    for name, s in styles.items():
        obj = {"font": s["font"], "size": s["size_sp"], "lineHeight": s["line_height_sp"],
               "tracking": s["tracking_sp"], "weight": s["weight"]}
        out.append(f"    readonly property var {camel(name)}: ({js(obj)})")
    out.append("")
    out.append("    // camelCase names of every style above, in token order (for galleries and tests).")
    out.append(f"    readonly property var styleNames: {js([camel(n) for n in styles])}")
    out.append("")
    out.append("    function family(style) {")
    out.append('        return style.font === "brand" ? brandFamily : plainFamily;')
    out.append("    }")
    out.append("")
    out.append("    // A QML font value for a style (family, pixel size, weight, letter spacing).")
    out.append("    // lineHeight cannot live in a font: set Text.lineHeight and lineHeightMode yourself.")
    out.append("    function font(style) {")
    out.append("        const f = Qt.font({ family: family(style), pixelSize: style.size, weight: style.weight,")
    out.append("                           letterSpacing: style.tracking });")
    out.append("        // Exact weight and optical size through font.variableAxes (Qt 6.7+, the minimum; see D31).")
    out.append("        const opsz = Fonts.textAxes.opsz;")
    out.append("        f.variableAxes = ({ \"wght\": style.weight,")
    out.append("                            \"opsz\": Math.max(opsz.min, Math.min(opsz.max, style.size)) });")
    out.append("        return f;")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_fonts(fonts):
    out = [header("Font families and variation axes from theme/fonts.json.") + "QtObject {"]
    out.append("    // Family names exactly as the font files report them.")
    out.append(f'    readonly property string textFamily: "{fonts["text"]["family"]}"')
    out.append(f'    readonly property string iconFamily: "{fonts["icons"]["family"]}"')
    out.append("")
    out.append("    // Variation axes as {tag: {min, default, max}}.")
    out.append(f'    readonly property var textAxes: ({js(fonts["text"]["axes"])})')
    out.append(f'    readonly property var iconAxes: ({js(fonts["icons"]["axes"])})')
    out.append("}")
    return "\n".join(out) + "\n"


def camel_keys(value):
    """Recursively camelCase dict keys (snake_case -> snakeCase); other values pass through."""
    if isinstance(value, dict):
        return {camel(k): camel_keys(v) for k, v in value.items()}
    return value


def role_names(table):
    """Replace snake_case color role values with their QML property names."""
    return {k: (None if v is None else qml_name(v)) for k, v in table.items()}


def spec_values(value):
    """camelCase keys of a component token table; `*_color` values become Colors property names and
    `*_font` values Type style names."""
    if not isinstance(value, dict):
        return value
    out = {}
    for k, v in value.items():
        if k.endswith("_color"):
            v = qml_name(v)
        elif k.endswith("_font"):
            v = camel(v)
        out[camel(k)] = spec_values(v)
    return out


def gen_control_spec(c):
    def sizes(table):
        out = {}
        for key, spec in table.items():
            spec = dict(spec)
            if "label_style" in spec:
                spec["label_style"] = camel(spec["label_style"])
            out[key] = camel_keys(spec)
        return out

    out = [header("Button, icon button, switch, slider, progress, chip, list and tile specs from tokens/components.json (sizes in "
                  "px, colors as Colors property names, shapes in px or \"full\").") + "QtObject {"]
    out.append(f"    readonly property var stateOpacity: ({js(camel_keys(c['state_opacity']))})")
    out.append(f"    readonly property var buttonSizes: ({js(sizes(c['button']['sizes']))})")
    out.append(f"    readonly property var buttonTypes: "
               f"({js({k: camel_keys(role_names(v)) for k, v in c['button']['types'].items()})})")
    out.append(f"    readonly property var iconButtonSizes: ({js(sizes(c['icon_button']['sizes']))})")
    out.append(f"    readonly property var iconButtonTypes: "
               f"({js({k: camel_keys(role_names(v)) for k, v in c['icon_button']['types'].items()})})")
    for name in ("switch", "slider", "progress", "chip", "list", "tile"):
        out.append(f"    readonly property var {name}Spec: ({js(spec_values(c[name]))})")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_material_shapes(c):
    shapes = c["material_shapes"]
    out = [MARK,
           "// The M3 Expressive shape library from tokens/components.json (MaterialShapes.kt): vertices and",
           "// roundings before rounding is applied; ShapeMath.build() turns one into curves.",
           ".pragma library", "",
           f"var names = {json.dumps(shapes['names'])};",
           "var shapes = {"]
    for name in shapes["names"]:
        out.append(f"    {name}: {json.dumps(shapes['shapes'][name], separators=(',', ':'))},")
    out.append("};")
    return "\n".join(out) + "\n"


def gen_colors(roles, fallback):
    dark = {r: fallback["colors"]["dark"][r] for r in roles}
    light = {r: fallback["colors"]["light"][r] for r in roles}
    out = [header("Color roles from theme/roles.json. Fallback is the golden palette (seed #134aae) "
                  "until palette.json loads.", qt="QtQuick") + "QtObject {"]
    out.append('    property string mode: "dark"')
    out.append(f'    property string sourceColor: "{fallback["source_color"]}"')
    out.append("    property bool loaded: false")
    out.append('    property string lastError: ""')
    out.append(f"    readonly property var roles: {js(roles)}")
    out.append(f"    property var tables: ({js({'dark': dark, 'light': light})})")
    out.append("")
    for r in roles:
        out.append(f'    readonly property color {qml_name(r)}: tables[mode]["{r}"]')
    out.append("")
    out.append("    // Returns an error string, or \"\" when the document is a valid palette.")
    out.append("    function validate(doc) {")
    out.append("        if (!doc || doc.format !== 1) return \"format must be 1\";")
    out.append("        if (doc.mode !== \"dark\" && doc.mode !== \"light\") return \"bad mode\";")
    out.append("        if (!doc.colors || !doc.colors.dark || !doc.colors.light) return \"missing dark/light tables\";")
    out.append("        var hex = /^#[0-9a-f]{6}$/;")
    out.append("        var modes = [\"dark\", \"light\"];")
    out.append("        for (var m = 0; m < modes.length; m++) {")
    out.append("            for (var i = 0; i < roles.length; i++) {")
    out.append("                var v = doc.colors[modes[m]][roles[i]];")
    out.append("                if (typeof v !== \"string\" || !hex.test(v))")
    out.append("                    return \"bad or missing \" + modes[m] + \".\" + roles[i];")
    out.append("            }")
    out.append("        }")
    out.append("        return \"\";")
    out.append("    }")
    out.append("")
    out.append("    // Load palette.json text. On any problem the previous colors stay and false is returned.")
    out.append("    function load(text) {")
    out.append("        var doc;")
    out.append("        try { doc = JSON.parse(text); } catch (e) { lastError = \"invalid JSON\"; return false; }")
    out.append("        var err = validate(doc);")
    out.append("        if (err !== \"\") { lastError = err; return false; }")
    out.append("        tables = doc.colors;")
    out.append("        sourceColor = doc.source_color;")
    out.append("        mode = doc.mode;")
    out.append("        lastError = \"\";")
    out.append("        loaded = true;")
    out.append("        return true;")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def build():
    tokens = json.loads((ROOT / "tokens" / "m3e.json").read_text())
    roles = json.loads((ROOT / "theme" / "roles.json").read_text())["roles"]
    fallback = json.loads((ROOT / "theme" / "fixtures" / "palette-134aae-tonal-spot-dark.json").read_text())
    fonts = json.loads((ROOT / "theme" / "fonts.json").read_text())
    components = json.loads((ROOT / "tokens" / "components.json").read_text())
    for kind in ("text", "icons"):
        if not re.fullmatch(r"[A-Za-z0-9 ]+", fonts[kind]["family"]):
            raise SystemExit(f"font family {fonts[kind]['family']!r} has characters unsafe for generated QML")
    for r in roles:
        if not re.fullmatch(r"[a-z]+(_[a-z]+)*", r):
            raise SystemExit(f"unexpected role name {r!r}")
    names = [qml_name(r) for r in roles]
    if len(set(names)) != len(names):
        raise SystemExit("role names collide after camelCase")
    bad = [n for n in names if re.match(r"on[A-Z]", n)]
    if bad:
        raise SystemExit(f"role names {bad} would be parsed as QML signal handlers")
    return {
        "Shapes.qml": gen_shapes(tokens),
        "Elevation.qml": gen_elevation(tokens),
        "Motion.qml": gen_motion(tokens),
        "Type.qml": gen_type(tokens, fonts),
        "Fonts.qml": gen_fonts(fonts),
        "ControlSpec.qml": gen_control_spec(components),
        "MaterialShapes.js": gen_material_shapes(components),
        "Colors.qml": gen_colors(roles, fallback),
    }


def main(argv):
    files = build()
    if "--check" in argv:
        stale = [n for n, text in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        if stale:
            print(f"stale generated QML: {', '.join(stale)}; run `make generate`", file=sys.stderr)
            return 1
        print("generated QML is up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
