#!/usr/bin/env python3
"""Generate Rutile's Kvantum theme for Qt apps (D60): theme/apps/kvantum.svg and theme/apps/kvantum.kvconfig, both
matugen templates that the shell renders into ~/.config/Kvantum/Rutile/ with its palette (as the GTK files).

The look follows libadwaita as adw-gtk3 draws it in the GTK apps beside them (the maintainer's request: Qt apps
looking like GTK 3/4): buttons and entries filled with the text color at 10% (15% hovered, 30% pressed), 6 px
corners, accent-filled checks, radios, slider and progress, thin pill scrollbars, menus as rounded popovers with
rounded items, the same color roles as gtk.css. Our own drawing, not derived from another theme; element names
and keys follow Kvantum's documentation (doc/Theme-Making.pdf, doc/Theme-Config in its source).

Kvantum draws a widget from nine SVG objects per state (an interior and eight frame pieces, named
NAME-STATE[-top|-bottom|-left|-right|-topleft|...]), each scaled to its place, so every piece here is its own
object with exact bounds. `make generate` runs this; `make generate-check` fails if the files are stale.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_SVG = ROOT / "theme" / "apps" / "kvantum.svg"
OUT_CONFIG = ROOT / "theme" / "apps" / "kvantum.kvconfig"


def c(role):
    return "{{colors.%s.default.hex}}" % role


FG = c("on_surface")
ACCENT = c("primary")
ON_ACCENT = c("on_primary")
STATES = ["normal", "focused", "pressed", "toggled", "disabled"]
EDGE = 10            # the length of edge pieces and the interior's side; Kvantum stretches them


class Svg:
    def __init__(self):
        self.parts = []
        self.x = 0
        self.y = 0
        self.row = 0
        self.ids = set()

    def place(self, w, h):
        """A free spot for a w×h group of objects, left to right in rows."""
        if self.x + w > 1600:
            self.x = 0
            self.y += self.row + 8
            self.row = 0
        x, y = self.x, self.y
        self.x += w + 8
        self.row = max(self.row, h)
        return x, y

    def obj(self, name, x, y, w, h, shapes):
        """One object: a transparent rectangle gives it exact bounds, the shapes draw it."""
        assert name not in self.ids, name
        self.ids.add(name)
        self.parts.append(f'<g id="{name}"><rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#000000" '
                          f'fill-opacity="0"/>{"".join(shapes)}</g>')

    def text(self):
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- GENERATED by tools/gen_kvantum.py (a matugen template): do not edit. -->\n'
                f'<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="{self.y + self.row + 8}">\n'
                + "\n".join(self.parts) + "\n</svg>\n")


def fill(color, opacity):
    return f'fill="{color}" fill-opacity="{opacity:g}"'


def rect(x, y, w, h, color, opacity):
    if opacity <= 0:
        return ""
    return f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" {fill(color, opacity)}/>'


def corner_paths(x, y, f, rad, where, bg, border):
    """The corner piece `where` of a rounded box: a f×f square at (x, y), rounded with radius rad at its outer
    corner. bg: (color, opacity) or None; border: (color, opacity, width) or None."""
    def at(px, py):
        mx = f - px if "right" in where else px
        my = f - py if "bottom" in where else py
        return f"{x + mx:g},{y + my:g}"
    # one mirror flips the arc's direction, two restore it
    sweep = 1 if (("right" in where) == ("bottom" in where)) else 0
    out = []
    if bg and bg[1] > 0:
        if rad > 0:
            d = f"M{at(0, f)} L{at(0, rad)} A{rad:g},{rad:g} 0 0 {sweep} {at(rad, 0)} L{at(f, 0)} L{at(f, f)} Z"
        else:
            d = f"M{at(0, 0)} L{at(f, 0)} L{at(f, f)} L{at(0, f)} Z"
        out.append(f'<path d="{d}" {fill(*bg)}/>')
    if border and border[1] > 0:
        color, opacity, w = border
        h = w / 2
        r = max(rad - h, 0)
        if rad > 0:
            d = f"M{at(h, f)} L{at(h, rad)} A{r:g},{r:g} 0 0 {sweep} {at(rad, h)} L{at(f, h)}"
        else:
            d = f"M{at(h, f)} L{at(h, h)} L{at(f, h)}"
        out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-opacity="{opacity:g}" stroke-width="{w:g}"/>')
    return out


def box(svg, name, f, rad, bg=None, border=None, interior=True, suffix=""):
    """The nine objects of one state of a framed element: NAME (interior) and NAME-top, ... (frame)."""
    x, y = svg.place(2 * f + EDGE, 2 * f + EDGE)
    L = EDGE
    edge_bg = lambda *a: rect(*a, *bg) if bg else ""  # noqa: E731
    if interior:
        svg.obj(name + suffix, x + f, y + f, L, L, [edge_bg(x + f, y + f, L, L)])
    for where, (px, py) in {"topleft": (x, y), "topright": (x + f + L, y), "bottomleft": (x, y + f + L),
                            "bottomright": (x + f + L, y + f + L)}.items():
        svg.obj(f"{name}-{where}{suffix}", px, py, f, f, corner_paths(px, py, f, rad, where, bg, border))
    bw = border[2] if border else 0
    bline = (lambda *a: rect(*a, border[0], border[1])) if border else (lambda *a: "")
    svg.obj(f"{name}-top{suffix}", x + f, y, L, f, [edge_bg(x + f, y, L, f), bline(x + f, y, L, bw)])
    svg.obj(f"{name}-bottom{suffix}", x + f, y + f + L, L, f,
            [edge_bg(x + f, y + f + L, L, f), bline(x + f, y + f + L + f - bw, L, bw)])
    svg.obj(f"{name}-left{suffix}", x, y + f, f, L, [edge_bg(x, y + f, f, L), bline(x, y + f, bw, L)])
    svg.obj(f"{name}-right{suffix}", x + f + L, y + f, f, L,
            [edge_bg(x + f + L, y + f, f, L), bline(x + f + L + f - bw, y + f, bw, L)])


def element(svg, name, f, rad, looks, interior=True):
    """Every state of an element: looks maps a state to (bg, border); a missing state is not drawn."""
    for state, (bg, border) in looks.items():
        box(svg, f"{name}-{state}", f, rad, bg, border, interior)


def glyph(svg, name, size, shapes_at):
    x, y = svg.place(size, size)
    svg.obj(name, x, y, size, size, shapes_at(x, y))


def stroke(d, color, opacity, width):
    return (f'<path d="{d}" fill="none" stroke="{color}" stroke-opacity="{opacity:g}" stroke-width="{width:g}" '
            'stroke-linecap="round" stroke-linejoin="round"/>')


STATE_ALPHA = {"normal": 1.0, "focused": 1.0, "pressed": 1.0, "toggled": 1.0, "disabled": 0.38}


def chevrons(svg, base, states=STATES, color=FG):
    """Arrows like libadwaita's (pan-*-symbolic): BASE-up/-down/-left/-right-STATE in 16×16."""
    paths = {"down": "M4,6 L8,10 L12,6", "up": "M4,10 L8,6 L12,10",
             "right": "M6,4 L10,8 L6,12", "left": "M10,4 L6,8 L10,12"}
    for direction, d in paths.items():
        for state in states:
            glyph(svg, f"{base}-{direction}-{state}", 16, lambda x, y, d=d, state=state: [
                f'<g transform="translate({x},{y})">' + stroke(d, color, STATE_ALPHA[state], 1.5) + "</g>"])


def build():
    svg = Svg()
    tint = lambda a: (FG, a)  # noqa: E731     the text color at a, as libadwaita's alpha(currentColor, a)

    # buttons (PanelButtonCommand): filled, 6 px corners; the default button tinted with the accent
    element(svg, "button", 6, 6, {"normal": (tint(.10), None), "focused": (tint(.15), None),
                                  "pressed": (tint(.30), None), "toggled": (tint(.30), None),
                                  "disabled": (tint(.05), None)})
    box(svg, "button-default", 6, 6, (ACCENT, .30), None)
    # flat buttons (tool buttons, spin buttons, headers, tabs, item views, menu items)
    flat = {"normal": (None, None), "focused": (tint(.07), None), "pressed": (tint(.16), None),
            "toggled": (tint(.10), None), "disabled": (None, None)}
    element(svg, "tbutton", 6, 6, {**flat, "focused": (tint(.10), None), "pressed": (tint(.30), None),
                                   "toggled": (tint(.30), None)})
    element(svg, "spin", 6, 6, {**flat, "focused": (tint(.10), None), "pressed": (tint(.30), None)})
    element(svg, "header", 2, 0, flat)
    element(svg, "tab", 6, 6, flat)
    element(svg, "itemview", 6, 6, {**flat, "toggled": ((ACCENT, .25), None), "pressed": ((ACCENT, .30), None)})
    element(svg, "menuitem", 6, 6, {"normal": (None, None), "focused": (tint(.10), None),
                                    "pressed": (tint(.16), None), "toggled": (tint(.10), None),
                                    "disabled": (None, None)})
    element(svg, "menubaritem", 6, 6, {"normal": (None, None), "focused": (tint(.10), None),
                                       "pressed": (tint(.16), None), "toggled": (tint(.16), None),
                                       "disabled": (None, None)})
    # entries: filled; focused adds libadwaita's accent ring
    element(svg, "lineedit", 6, 6, {"normal": (tint(.10), None), "focused": (tint(.10), (ACCENT, .5, 2)),
                                    "pressed": (tint(.10), (ACCENT, .5, 2)), "toggled": (tint(.10), (ACCENT, .5, 2)),
                                    "disabled": (tint(.05), None)})
    # containers: a frame (1 px line), a group (card), the tab widget's pane
    element(svg, "common", 8, 8, {"normal": (None, (FG, .15, 1)), "disabled": (None, (FG, .08, 1))})
    element(svg, "group", 10, 10, {"normal": ((c("surface_container"), 1), None)})
    element(svg, "tabframe", 8, 8, {"normal": (None, (FG, .15, 1))})
    # popovers: menus and tooltips
    element(svg, "menu", 10, 10, {"normal": ((c("surface_container_high"), 1), (FG, .08, 1))})
    element(svg, "tooltip", 6, 6, {"normal": (("#000000", .8), None)})
    # progress and sliders: a trough at 15%, filled with the accent
    element(svg, "progress", 3, 3, {"normal": (tint(.15), None), "disabled": (tint(.08), None)})
    element(svg, "progress-pattern", 3, 3, {"normal": ((ACCENT, 1), None), "focused": ((ACCENT, 1), None),
                                            "disabled": (tint(.3), None)})
    element(svg, "slider", 2, 2, {"normal": (tint(.15), None), "focused": (tint(.15), None),
                                  "pressed": (tint(.15), None), "toggled": ((ACCENT, 1), None),
                                  "disabled": (tint(.08), None)})
    # scrollbars: a pill, no groove (libadwaita's overlay scrollbars)
    element(svg, "scrollbarslider", 4, 4, {"normal": (tint(.20), None), "focused": (tint(.40), None),
                                           "pressed": (tint(.60), None), "disabled": (tint(.10), None)},
            interior=False)
    element(svg, "scrollgroove", 1, 0, {"normal": (None, None)})
    # bars and windows
    element(svg, "toolbar", 1, 0, {"normal": (None, None)})
    element(svg, "dock", 1, 0, {"normal": ((c("surface_container"), 1), None)})
    element(svg, "titlebar", 1, 0, {"normal": ((c("surface_container"), 1), None),
                                    "focused": ((c("surface_container"), 1), None)})
    element(svg, "splitter", 1, 0, {"normal": (None, None), "focused": (tint(.10), None), "pressed": (tint(.2), None)})
    # the keyboard focus ring (no states), rounded like the widgets it goes around
    box(svg, "focus", 6, 6, None, (ACCENT, .5, 2), interior=False)

    # check boxes and radio buttons (16 px), as libadwaita's
    for kind in ("checkbox", "radio"):
        rad = 4 if kind == "checkbox" else 8
        for state in ("normal", "focused", "pressed", "disabled"):
            a = {"normal": .30, "focused": .45, "pressed": .6, "disabled": .15}[state]
            glyph(svg, f"{kind}-{state}", 16, lambda x, y, a=a, rad=rad: [
                f'<rect x="{x + 1}" y="{y + 1}" width="14" height="14" rx="{rad - 1}" fill="none" stroke="{FG}" '
                f'stroke-opacity="{a:g}" stroke-width="2"/>'])
            on = 1 if state != "disabled" else .4
            if kind == "checkbox":
                mark = lambda x, y: stroke(f"M{x + 4},{y + 8} L{x + 7},{y + 11} L{x + 12},{y + 5}", ON_ACCENT, 1, 2)  # noqa: E731
                dash = lambda x, y: stroke(f"M{x + 4.5},{y + 8} L{x + 11.5},{y + 8}", ON_ACCENT, 1, 2)  # noqa: E731
            else:
                mark = lambda x, y: f'<circle cx="{x + 8}" cy="{y + 8}" r="3" fill="{ON_ACCENT}"/>'  # noqa: E731
                dash = mark
            hover = .9 if state == "focused" else 1
            glyph(svg, f"{kind}-checked-{state}", 16, lambda x, y, rad=rad, on=on, hover=hover, mark=mark: [
                f'<rect x="{x}" y="{y}" width="16" height="16" rx="{rad}" fill="{ACCENT}" fill-opacity="{on * hover:g}"/>',
                mark(x, y)])
            glyph(svg, f"{kind}-tristate-{state}", 16, lambda x, y, rad=rad, on=on, dash=dash: [
                f'<rect x="{x}" y="{y}" width="16" height="16" rx="{rad}" fill="{ACCENT}" fill-opacity="{on:g}"/>',
                dash(x, y)])

    # the slider's handle: a round knob in the text color (libadwaita's is light on dark)
    for state in ("normal", "focused", "pressed", "disabled"):
        o = {"normal": 1, "focused": 1, "pressed": 1, "disabled": .4}[state]
        glyph(svg, f"slidercursor-{state}", 20, lambda x, y, o=o: [
            f'<circle cx="{x + 10}" cy="{y + 10}" r="9" fill="{FG}" fill-opacity="{o:g}"/>'])
    glyph(svg, "slider-tick", 5, lambda x, y: [rect(x, y + 2, 5, 1, FG, .3)])

    # arrows everywhere, the tree expander, menus' submenu arrows
    chevrons(svg, "arrow")
    for state in STATES:
        glyph(svg, f"arrow-plus-{state}", 16, lambda x, y, s=state: [
            f'<g transform="translate({x},{y})">' + stroke("M6,4 L10,8 L6,12", FG, STATE_ALPHA[s], 1.5) + "</g>"])
        glyph(svg, f"arrow-minus-{state}", 16, lambda x, y, s=state: [
            f'<g transform="translate({x},{y})">' + stroke("M4,6 L8,10 L12,6", FG, STATE_ALPHA[s], 1.5) + "</g>"])
    for direction, d in {"right": "M6,4 L10,8 L6,12", "left": "M10,4 L6,8 L10,12"}.items():
        for state in ("normal", "focused", "pressed", "disabled"):
            glyph(svg, f"menuitem-{direction}-{state}", 16, lambda x, y, d=d, s=state: [
                f'<g transform="translate({x},{y})">' + stroke(d, FG, STATE_ALPHA[s], 1.5) + "</g>"])
    glyph(svg, "menuitem-separator", 10, lambda x, y: [rect(x, y + 4.5, 10, 1, FG, .15)])
    for state in ("normal", "focused"):
        glyph(svg, f"menuitem-tearoff-{state}", 10, lambda x, y: [rect(x, y + 4.5, 5, 1, FG, .3)])

    # tab close buttons: an x in a circle on hover
    for state in ("normal", "focused", "pressed", "disabled", "toggled"):
        bg = {"focused": .15, "pressed": .3}.get(state, 0)
        a = .38 if state == "disabled" else 1
        glyph(svg, f"tab-close-{state}", 16, lambda x, y, bg=bg, a=a: [
            f'<circle cx="{x + 8}" cy="{y + 8}" r="8" fill="{FG}" fill-opacity="{bg:g}"/>' if bg else "",
            stroke(f"M{x + 5},{y + 5} L{x + 11},{y + 11} M{x + 11},{y + 5} L{x + 5},{y + 11}", FG, a, 1.5)])
    glyph(svg, "tab-tear", 2, lambda x, y: [rect(x, y, 2, 2, FG, .2)])

    # small marks: separators, grips, the default button's indicator (unused: it is tinted instead)
    glyph(svg, "header-separator", 2, lambda x, y: [rect(x, y, 1, 2, FG, .15)])
    glyph(svg, "toolbar-separator", 4, lambda x, y: [rect(x + 1.5, y, 1, 4, FG, .15)])
    glyph(svg, "toolbar-handle", 8, lambda x, y: [])
    for state in ("normal", "focused", "pressed"):
        glyph(svg, f"splitter-grip-{state}", 16, lambda x, y: [])
        glyph(svg, f"grip-{state}", 13, lambda x, y: [])
    for state in ("normal", "focused"):
        glyph(svg, f"sizegrip-{state}", 13, lambda x, y: [
            f'<circle cx="{x + px}" cy="{y + py}" r="1" fill="{FG}" fill-opacity=".3"/>'
            for px, py in ((11, 5), (8, 8), (11, 8), (5, 11), (8, 11), (11, 11))])
    glyph(svg, "button-default-indicator", 9, lambda x, y: [])

    # the title bar buttons of windows inside windows (QMdiSubWindow), as libadwaita's window controls
    marks = {"close": "M5,5 L11,11 M11,5 L5,11", "maximize": "M5,5 L11,5 L11,11 L5,11 Z",
             "restore": "M6,7 L11,7 L11,11 L6,11 Z M7,5 L12,5 L12,9", "minimize": "M5,11 L11,11",
             "shade": "M4,10 L8,6 L12,10"}
    for name, d in marks.items():
        for state in ("normal", "focused", "pressed", "disabled"):
            bg = {"normal": .10, "focused": .15, "pressed": .30, "disabled": .05}[state]
            glyph(svg, f"mdi-{name}-{state}", 16, lambda x, y, d=d, bg=bg: [
                f'<circle cx="{x + 8}" cy="{y + 8}" r="8" fill="{FG}" fill-opacity="{bg:g}"/>',
                f'<g transform="translate({x},{y})">' + stroke(d, FG, 1, 1.2) + "</g>"])
    glyph(svg, "mdi-menu-normal", 16, lambda x, y: [])

    # dials (QDial)
    glyph(svg, "dial", 32, lambda x, y: [f'<circle cx="{x + 16}" cy="{y + 16}" r="15" fill="{FG}" fill-opacity=".1"/>'])
    glyph(svg, "dial-handle", 8, lambda x, y: [f'<circle cx="{x + 4}" cy="{y + 4}" r="3" fill="{ACCENT}"/>'])
    glyph(svg, "dial-notches", 32, lambda x, y: [])
    return svg


